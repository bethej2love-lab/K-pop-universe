drop function if exists public.log_seo_event(text,text,text,text,text,text,text);
create or replace function public.log_seo_event(p_ev text, p_type text, p_path text, p_src text, p_did text, p_ua text default null, p_vid text default null, p_grp text default null)
returns void language plpgsql security definer set search_path=public as $$
begin
  if p_ev not in ('land','play','cta','to_app','yt','eng','fav') then return; end if;
  insert into public.seo_events(ev,page_type,path,src,did,ua,vid,grp)
  values (p_ev, left(coalesce(p_type,''),20), left(coalesce(p_path,''),200), left(coalesce(p_src,''),80), left(coalesce(p_did,''),40), left(p_ua,160),
          case when p_vid ~ '^[A-Za-z0-9_-]{11}$' then p_vid end, left(p_grp,60));
end $$;
revoke all on function public.log_seo_event(text,text,text,text,text,text,text,text) from public;
grant execute on function public.log_seo_event(text,text,text,text,text,text,text,text) to anon, authenticated;

-- 그룹별 이번 주(7일) 본 사람 — 정적 페이지 사람(출처 있거나 행동 있는 기기, 봇 UA 제외) + 앱(그룹·멤버 카드 연 계정). 30명 이상만. 1시간 캐시.
create or replace function public.get_week_viewers()
returns jsonb language plpgsql security definer set search_path=public as $$
declare cr record; d jsonb;
begin
  select * into cr from public._hot_fancams_cache where k='viewers';
  if found and cr.at > now() - interval '1 hour' then return cr.data; end if;
  with act as (
    select distinct did from public.seo_events where created_at > now() - interval '7 days' and ev in ('play','eng','cta','to_app','yt','fav')
  ), web as (
    select e.grp, e.did from public.seo_events e
     where e.created_at > now() - interval '7 days' and e.grp is not null and e.did <> ''
       and coalesce(e.ua,'') !~* '(bot|spider|crawl|yeti|daumoa|slurp|bytespider|gpt|perplexity|claude|preview|inspection|mediapartners|headless)'
       and (coalesce(e.src,'') <> '' or e.did in (select did from act))
  ), app as (
    select k as grp, user_id::text as did from public.app_events
     where created_at > now() - interval '7 days' and ev in ('view_group','view_member') and k is not null
  ), u as (select grp, did from web union select grp, did from app)
  select jsonb_build_object('at', now(), 'g', coalesce(jsonb_object_agg(grp, n), '{}'::jsonb)) into d
    from (select grp, count(distinct did) n from u group by grp having count(distinct did) >= 30) x;
  insert into public._hot_fancams_cache(k, at, data) values ('viewers', now(), d)
    on conflict (k) do update set at = excluded.at, data = excluded.data;
  return d;
end $$;
revoke all on function public.get_week_viewers() from public;
grant execute on function public.get_week_viewers() to anon, authenticated;

select count(*) filled, public.get_week_viewers() v from public.seo_events where grp is not null;
