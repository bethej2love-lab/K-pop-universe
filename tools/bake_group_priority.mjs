// 곱해지므로, 크기 차이 최대 1.94배를 등급이 충분히 뒤집는다.
const MULT = { A: 4, B: 1.5, C: 0.6 };

import path from 'path';
import { fileURLToPath } from 'url';
const F = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'groups.json');
const g = JSON.parse(fs.readFileSync(F, 'utf8'));
const keys = Object.keys(g);

const missA = A.filter(k => !g[k]);
const missC = C.filter(k => !g[k]);
if (missA.length || missC.length) {
  console.log('⚠️ groups.json에 없는 이름:', [...missA, ...missC].join(', '));
}

let a = 0, b = 0, c = 0;
keys.forEach(k => {
  const lv = A.includes(k) ? 'A' : C.includes(k) ? 'C' : 'B';
  if (lv === 'A') a++; else if (lv === 'C') c++; else b++;
  const m = MULT[lv];
  if (m === 1) delete g[k].pri; else g[k].pri = m;
});

fs.writeFileSync(F, JSON.stringify(g, null, 2));
console.log(`등급 반영: A ${a}개(×${MULT.A}) · B ${b}개(×${MULT.B}) · C ${c}개(×${MULT.C}) / 총 ${keys.length}`);
const sample = ['뉴진스','에스파','세븐틴','파이브돌스','나인뮤지스'];
