const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.join(__dirname,'..'),c={};vm.createContext(c);
vm.runInContext(fs.readFileSync(path.join(root,'shared.js'),'utf8'),c);
const app=fs.readFileSync(path.join(root,'app.js'),'utf8'),a=app.indexOf('function _songTitleAmbiguous('),b=app.indexOf('\nasync function _openSongVideos',a);
vm.runInContext(app.slice(a,b),c);
const index=JSON.parse(fs.readFileSync(path.join(root,'tracks_index.json'),'utf8'));
assert.equal(c._songTitleAmbiguous(index,'고스트나인',null,'moonlight'),true,'actual catalog has other Moonlight recordings');
assert.equal(c._songTitleAmbiguous(null,'고스트나인',null,'moonlight'),true,'missing catalog is not proof of uniqueness');
const owner={key:'고스트나인:moonlight',names:['고스트나인','GHOST9'],groupKey:'고스트나인',personKeys:[],ambiguous:true};
const check=(v,want)=>assert.equal(c._songCoverByTitle(v,'moonlight',owner),want,v.title);
check({title:"TWICE 'Moonlight' fancam",song_keys:['트와이스:moonlight']},false);
check({title:"GHOST9 'Moonlight' cover",song_keys:['트와이스:moonlight']},false);
check({title:"Artist - Moonlight cover"},false);
check({title:"GHOST9 - 'Moonlight' dance cover"},true);
check({title:"Artist - Moonlight",cover_of_groups:['고스트나인']},true);
check({title:'Artist - Moonlight',song_keys:['고스트나인:moonlight']},true);
check({title:"Artist - Moonlight",song_keys:['트와이스:moonlightsunrise']},false);
const iu={key:'아이유:잔소리',names:['아이유','IU'],personKeys:['아이유(솔로)'],ambiguous:true};
assert.equal(c._songCoverByTitle({title:'아이즈원 - 잔소리',cover_of_members:['아이유(솔로)']},'잔소리',iu),true,'verified original-artist tag keeps a legitimate cover');
assert.equal(c._songCoverByTitle({title:'HUI - 잔소리'},'잔소리',iu),false,'IU is not a substring match inside HUI');
